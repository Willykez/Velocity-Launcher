@Composable
fun WidgetPickerDialog(
    onDismiss: () -> Unit,
    onSelectWidget: (String) -> Unit
) {
    Dialog(onDismissRequest = onDismiss) {
        Card(
            modifier = Modifier
                .fillMaxWidth()
                .padding(16.dp)
                .testTag("widget_picker_dialog"),
            shape = RoundedCornerShape(24.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
            elevation = CardDefaults.cardElevation(defaultElevation = 8.dp)
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(vertical = 12.dp)
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 20.dp, vertical = 8.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = "Add Smart Widget",
                        fontSize = 18.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    IconButton(onClick = onDismiss) {
                        Icon(Icons.Default.Close, contentDescription = "Close")
                    }
                }

                HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.5f))

                WidgetPickerItemRow(
                    title = "System Telemetry Strip",
                    desc = "Storage meter, RAM usage, and quick toggles",
                    icon = Icons.Default.DataUsage,
                    onClick = { onSelectWidget("SYSTEM_TELEMETRY") }
                )

                WidgetPickerItemRow(
                    title = "Quick Note Sticky Pad",
                    desc = "Interactive memo pad with custom accent colors",
                    icon = Icons.Default.NoteAlt,
                    onClick = { onSelectWidget("QUICK_NOTE") }
                )

                WidgetPickerItemRow(
                    title = "Mini Music Controller",
                    desc = "Media playback strip with play, skip, and progress",
                    icon = Icons.Default.MusicNote,
                    onClick = { onSelectWidget("MUSIC_PLAYER") }
                )
            }
        }
    }
}

@Composable
private fun WidgetPickerItemRow(
    title: String,
    desc: String,
    icon: ImageVector,
    onClick: () -> Unit
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick)
            .padding(horizontal = 20.dp, vertical = 14.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Icon(
            imageVector = icon,
            contentDescription = title,
            tint = MaterialTheme.colorScheme.primary,
            modifier = Modifier.size(24.dp)
        )
        Spacer(modifier = Modifier.width(16.dp))
        Column(modifier = Modifier.weight(1f)) {
            Text(title, fontWeight = FontWeight.Bold, fontSize = 14.sp)
            Text(desc, fontSize = 11.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}
